// 在真实文件系统验证副本、租约和冻结差异；不 mock 工作区规则。
import { mkdtemp, mkdir, writeFile, readFile, symlink, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, expect, it } from 'vitest';
import { WorkspaceService } from '../workspaceService.js';
const roots: string[] = [];
afterEach(async () => { for (const root of roots.splice(0)) await rm(root, { recursive: true, force: true }); });
it('保留 dirty/untracked 与内部依赖，租约互斥；冻结新增/删除/二进制/权限，原目录不变', async () => {
  const base = await mkdtemp(join(tmpdir(), 'hcode-workspace-')); roots.push(base);
  const source = join(base, 'source'); await mkdir(join(source, '.git'), { recursive: true });
  await writeFile(join(source, 'dirty.js'), 'old\n'); await writeFile(join(source, 'remove.txt'), 'delete');
  await mkdir(join(source, 'node_modules')); await writeFile(join(source, 'node_modules', 'dependency.js'), 'module');
  const service = new WorkspaceService(join(base, 'records'));
  const workspace = await service.create(source, 'candidate');
  expect(await readFile(join(workspace.path, 'node_modules/dependency.js'), 'utf8')).toBe('module');
  const release = service.acquire(workspace.id, 'execution');
  expect(() => service.acquire(workspace.id, 'review')).toThrow(/租约/);
  const tools = service.writerTools(workspace, 'execution');
  await tools[0]!.execute({ path: 'dirty.js', content: 'new\n', expectedHash: await service.fileHash(workspace, 'dirty.js') });
  await tools[0]!.execute({ path: 'new.txt', content: 'added', expectedHash: null });
  await tools[1]!.execute({ path: 'remove.txt', expectedHash: await service.fileHash(workspace, 'remove.txt') });
  await writeFile(join(workspace.path, 'binary.bin'), Buffer.from([0, 255]));
  release();
  await expect(tools[0]!.execute({ path: 'escape.txt', content: 'no', expectedHash: null })).rejects.toThrow(/租约/);
  const version = await service.freeze(workspace, 1);
  expect(version.changes.map((entry) => entry.path)).toEqual(['binary.bin', 'dirty.js', 'new.txt', 'remove.txt']);
  expect(version.changes[0]!.binary).toBe(true);
  expect(await readFile(join(source, 'dirty.js'), 'utf8')).toBe('old\n');
  await service.assertCurrent(workspace, version);
  await writeFile(join(workspace.path, 'dirty.js'), 'manual');
  await expect(service.assertCurrent(workspace, version)).rejects.toThrow(/变化/);
});
it('拒绝外部依赖链接和写入路径逃逸，不借副本写回原项目', async () => {
  const base = await mkdtemp(join(tmpdir(), 'hcode-workspace-')); roots.push(base);
  const source = join(base, 'source'); await mkdir(join(source, '.git'), { recursive: true });
  await symlink(base, join(source, 'outside'));
  const service = new WorkspaceService(join(base, 'records'));
  await expect(service.create(source, 'bad')).rejects.toThrow(/外部/);
  await rm(join(source, 'outside'));
  const workspace = await service.create(source, 'good');
  const release = service.acquire(workspace.id, 'writer');
  const tool = service.writerTools(workspace, 'writer')[0]!;
  await expect(tool.execute({ path: '../outside', content: 'bad', expectedHash: null })).rejects.toThrow(/路径/);
  await expect(tool.execute({ path: '.git/config', content: 'bad', expectedHash: null })).rejects.toThrow(/路径/);
  await expect(tool.execute({ path: 'node_modules/dep', content: 'bad', expectedHash: null })).rejects.toThrow(/依赖/);
  release();
});
it('审查读取独立冻结基线，丢弃副本后仍能核对冻结差异', async () => {
  const base = await mkdtemp(join(tmpdir(), 'hcode-baseline-')); roots.push(base);
  const source = join(base, 'source'); await mkdir(source);
  await writeFile(join(source, 'test.js'), 'original assertion\n');
  const service = new WorkspaceService(join(base, 'records'));
  const workspace = await service.create(source, 'baseline');
  await writeFile(join(workspace.path, 'test.js'), 'candidate assertion\n');
  const version = await service.freeze(workspace, 1);
  const tool = service.reviewTools(workspace)[0]!;
  expect(JSON.stringify(await tool.execute({ path: 'test.js' }))).toContain('original assertion');
  await expect(tool.execute({ path: '../project/test.js' })).rejects.toThrow();
  await writeFile(join(source, 'test.js'), 'later original change\n');
  expect(JSON.stringify(await tool.execute({ path: 'test.js' }))).toContain('original assertion');
  await service.discard(workspace);
  const preview = await service.preview(workspace, version);
  expect(preview.changes).toEqual([{ path: 'test.js', binary: false, before: 'original assertion\n', after: 'candidate assertion\n' }]);
  expect(await readFile(join(source, 'test.js'), 'utf8')).toBe('later original change\n');
});
